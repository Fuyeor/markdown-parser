// packages/linkify/build/generate-tlds.ts
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

// md is intentionally omitted so Markdown filenames are not fuzzy links.
const CC_TLDS = `
ac ad ae af ag ai al am ao aq ar as at au aw ax az
ba bb bd be bf bg bh bi bj bm bn bo br bs bt bv bw by bz
ca cc cd cf cg ch ci ck cl cm cn co cr cu cv cw cx cy cz
de dj dk dm do dz
ec ee eg er es et eu
fi fj fk fm fo fr
ga gb gd ge gf gg gh gi gl gm gn gp gq gr gs gt gu gw gy
hk hm hn hr ht hu
id ie il im in io iq ir is it
je jm jo jp
ke kg kh ki km kn kp kr kw ky kz
la lb lc li lk lr ls lt lu lv ly
ma mc me mg mh mk ml mm mn mo mp mq mr ms mt mu mv mw mx my mz
na nc ne nf ng ni nl no np nr nu nz
om
pa pe pf pg ph pk pl pm pn pr ps pt pw py
qa
re ro rs ru rw
sa sb sc sd se sg sh si sj sk sl sm sn so sr ss st su sv sx sy sz
tc td tf tg th tj tk tl tm tn to tr tt tv tw tz
ua ug uk us uy uz
va vc ve vg vi vn vu
wf ws
ye yt
za zm zw
`
  .trim()
  .split(/\s+/);

const OUTPUT_PATH = resolve(import.meta.dirname, '../src/cc-tld-bitmap.ts');
const BIT_COUNT = 26 * 26;
const WORD_COUNT = Math.ceil(BIT_COUNT / 32);
const bitmap = new Uint32Array(WORD_COUNT);

for (const tld of CC_TLDS) {
  if (!/^[a-z]{2}$/.test(tld) || tld === 'md') {
    throw new Error(`Invalid ccTLD entry: ${tld}`);
  }

  const bitIndex = (tld.charCodeAt(0) - 97) * 26 + tld.charCodeAt(1) - 97;
  bitmap[bitIndex >> 5] |= 1 << (bitIndex & 31);
}

const words = Array.from(bitmap, (word) => `0x${word.toString(16)}`);
const source = `// packages/linkify/src/cc-tld-bitmap.ts
// This file is generated by build/generate-tlds.ts. Do not edit manually.

export const CC_TLD_BITMAP = new Uint32Array([${words.join(', ')}]);
`;

mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
writeFileSync(OUTPUT_PATH, source);
console.log(`Generated ${OUTPUT_PATH} from ${CC_TLDS.length} ccTLDs.`);
